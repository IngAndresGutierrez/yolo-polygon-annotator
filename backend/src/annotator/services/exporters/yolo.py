"""YOLO label formatting (Ultralytics conventions).

Detection:     `class x_center y_center width height`
Segmentation:  `class x1 y1 x2 y2 x3 y3 x4 y4`

All values are normalized to [0, 1] by the image width/height. Segmentation
keeps the canonical vertex order (TL, TR, BR, BL for axis-aligned boxes).
"""

from __future__ import annotations

from collections.abc import Sequence

from annotator.services.validators.geometry import bounding_box, order_quad

Coord = tuple[float, float]
PRECISION = 6


def _clamp01(value: float) -> float:
    return min(max(value, 0.0), 1.0)


def _fmt(value: float) -> str:
    text = f"{value:.{PRECISION}f}"
    return "0.000000" if text == "-0.000000" else text


def normalize_point(x: float, y: float, width: int, height: int) -> Coord:
    return _clamp01(x / width), _clamp01(y / height)


def detection_values(points: Sequence[Coord], width: int, height: int) -> tuple[float, ...]:
    xmin, ymin, xmax, ymax = bounding_box(points)
    nx1, ny1 = normalize_point(xmin, ymin, width, height)
    nx2, ny2 = normalize_point(xmax, ymax, width, height)
    return (nx1 + nx2) / 2, (ny1 + ny2) / 2, nx2 - nx1, ny2 - ny1


def detection_line(class_id: int, points: Sequence[Coord], width: int, height: int) -> str:
    values = detection_values(points, width, height)
    return " ".join([str(class_id), *(_fmt(v) for v in values)])


def segmentation_line(class_id: int, points: Sequence[Coord], width: int, height: int) -> str:
    coords: list[str] = []
    for x, y in order_quad(points):
        nx, ny = normalize_point(x, y, width, height)
        coords.extend((_fmt(nx), _fmt(ny)))
    return " ".join([str(class_id), *coords])


def build_data_yaml(class_names: dict[int, str], include_test: bool) -> str:
    """Ultralytics dataset YAML with paths relative to the YAML file itself.

    `path` is intentionally omitted: Ultralytics then uses the directory that
    contains `data.yaml` as the dataset root, so the folder can be moved or
    unzipped anywhere without editing it.
    """
    lines = [
        "# Ultralytics YOLO dataset generated by YOLO Polygon Annotator.",
        "# Paths are relative to the directory containing this file.",
        "train: images/train",
        "val: images/val",
    ]
    if include_test:
        lines.append("test: images/test")
    lines.append(f"nc: {len(class_names)}")
    lines.append("names:")
    for class_id in sorted(class_names):
        escaped = class_names[class_id].replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'  {class_id}: "{escaped}"')
    return "\n".join(lines) + "\n"
